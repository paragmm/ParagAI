"""Dataset loaders and dynamic batching for autoregressive language modeling."""

import numpy as np
import torch

from paragai.tokenizer.base import BaseTokenizer


class TextDataset:
    """Memory-efficient text dataset with dynamic autoregressive batching."""

    def __init__(
        self,
        token_ids: np.ndarray,
        val_ratio: float = 0.1,
    ):
        self.data = token_ids
        split_idx = int(len(self.data) * (1.0 - val_ratio))
        self.train_data = self.data[:split_idx]
        self.val_data = self.data[split_idx:]

    @classmethod
    def from_text(
        cls,
        text: str,
        tokenizer: BaseTokenizer,
        val_ratio: float = 0.1,
    ) -> "TextDataset":
        """Tokenize raw text string into numpy array and create dataset."""
        tokens = tokenizer.encode(text)
        token_array = np.array(tokens, dtype=np.int32)
        return cls(token_array, val_ratio=val_ratio)

    @classmethod
    def from_file(
        cls,
        file_path: str,
        tokenizer: BaseTokenizer,
        val_ratio: float = 0.1,
    ) -> "TextDataset":
        """Load text from file and tokenize."""
        with open(file_path, "r", encoding="utf-8") as f:
            text = f.read()
        return cls.from_text(text, tokenizer, val_ratio=val_ratio)

    def get_batch(
        self,
        split: str,
        batch_size: int,
        seq_len: int,
        device: torch.device,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Sample a batch of inputs X and targets Y where Y is X shifted by 1."""
        data = self.train_data if split == "train" else self.val_data
        if len(data) <= seq_len:
            raise ValueError(
                f"Data size ({len(data)}) must be strictly greater than seq_len ({seq_len})"
            )

        max_start = len(data) - seq_len - 1
        start_indices = np.random.randint(0, max_start + 1, size=batch_size)

        x_batch = np.stack([data[i : i + seq_len] for i in start_indices])
        y_batch = np.stack([data[i + 1 : i + seq_len + 1] for i in start_indices])

        x_tensor = torch.tensor(x_batch, dtype=torch.long, device=device)
        y_tensor = torch.tensor(y_batch, dtype=torch.long, device=device)

        return x_tensor, y_tensor


class SFTDataset:
    """Supervised Fine-Tuning dataset with assistant response loss masking (-100).

    Computes cross-entropy loss exclusively on tokens generated by the `<|assistant|>`
    role (including the closing `<|end|>` token). Prompt tokens from `<|system|>` and
    `<|user|>` segments, as well as padding positions, are masked with -100 (ignore_index).
    """

    def __init__(
        self,
        samples: list[tuple[np.ndarray, np.ndarray]],
        val_ratio: float = 0.1,
        pad_token_id: int = 0,
    ):
        self.samples = samples
        self.pad_token_id = pad_token_id
        if not samples:
            raise ValueError("SFTDataset received an empty sample list.")

        split_idx = max(1, int(len(self.samples) * (1.0 - val_ratio)))
        self.train_samples = self.samples[:split_idx]
        self.val_samples = self.samples[split_idx:] if split_idx < len(self.samples) else self.samples[:1]

    @classmethod
    def from_text(
        cls,
        text: str,
        tokenizer: BaseTokenizer,
        val_ratio: float = 0.1,
    ) -> "SFTDataset":
        """Parse structured chat text and build masked SFT (input, target) pairs."""
        chunks = text.split("\n\n")
        samples: list[tuple[np.ndarray, np.ndarray]] = []

        # Find token IDs for assistant and end markers
        asst_id = getattr(tokenizer, "ASSISTANT_ID", None)
        end_id = getattr(tokenizer, "END_ID", None)
        if hasattr(tokenizer, "token_to_id"):
            asst_id = tokenizer.token_to_id("<|assistant|>") or asst_id
            end_id = tokenizer.token_to_id("<|end|>") or end_id
        if asst_id is None or end_id is None:
            enc_asst = tokenizer.encode("<|assistant|>", add_special_tokens=False)
            enc_end = tokenizer.encode("<|end|>", add_special_tokens=False)
            asst_id = enc_asst[0] if enc_asst else 6
            end_id = enc_end[0] if enc_end else 7

        im_end_id = getattr(tokenizer, "IM_END_ID", 9)

        for chunk in chunks:
            chunk = chunk.strip()
            if not chunk:
                continue

            token_ids = tokenizer.encode(chunk, add_special_tokens=False)
            if len(token_ids) < 3:
                continue

            labels = np.full(len(token_ids), -100, dtype=np.int64)
            in_assistant = False

            for idx, tid in enumerate(token_ids):
                if tid == asst_id:
                    in_assistant = True
                    continue
                elif tid in (end_id, im_end_id) and in_assistant:
                    labels[idx] = tid
                    in_assistant = False
                    continue

                if in_assistant:
                    labels[idx] = tid

            if (labels != -100).any():
                x = np.array(token_ids[:-1], dtype=np.int64)
                y = np.array(labels[1:], dtype=np.int64)
                samples.append((x, y))

        if not samples:
            tokens = tokenizer.encode(text, add_special_tokens=False)
            x = np.array(tokens[:-1], dtype=np.int64)
            y = np.array(tokens[1:], dtype=np.int64)
            samples.append((x, y))

        pad_id = getattr(tokenizer, "PAD_ID", 0)
        return cls(samples, val_ratio=val_ratio, pad_token_id=pad_id)

    @classmethod
    def from_file(
        cls,
        file_path: str,
        tokenizer: BaseTokenizer,
        val_ratio: float = 0.1,
    ) -> "SFTDataset":
        """Load SFT text from file and tokenize with loss masking."""
        with open(file_path, "r", encoding="utf-8") as f:
            text = f.read()
        return cls.from_text(text, tokenizer, val_ratio=val_ratio)

    def get_batch(
        self,
        split: str,
        batch_size: int,
        seq_len: int,
        device: torch.device,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Sample a batch of inputs X and masked targets Y of shape (batch_size, seq_len)."""
        pool = self.train_samples if split == "train" else self.val_samples
        indices = np.random.randint(0, len(pool), size=batch_size)

        x_batch = []
        y_batch = []

        for idx in indices:
            x_raw, y_raw = pool[idx]
            n = len(x_raw)
            if n >= seq_len:
                start = np.random.randint(0, n - seq_len + 1) if n > seq_len else 0
                x_seq = x_raw[start : start + seq_len]
                y_seq = y_raw[start : start + seq_len]
            else:
                pad_len = seq_len - n
                x_seq = np.pad(x_raw, (0, pad_len), constant_values=self.pad_token_id)
                y_seq = np.pad(y_raw, (0, pad_len), constant_values=-100)

            x_batch.append(x_seq)
            y_batch.append(y_seq)

        x_tensor = torch.tensor(np.stack(x_batch), dtype=torch.long, device=device)
        y_tensor = torch.tensor(np.stack(y_batch), dtype=torch.long, device=device)
        return x_tensor, y_tensor
